"""Write docs/category_mapping.md: outcome and intervention category tables (patterns + distribution).

Regenerated by `finalize_cohort` on every rebuild, so the tables always match the code, the
config and the included cohort. Do not edit the output by hand.
"""

from __future__ import annotations

import re
from collections import Counter, OrderedDict
from pathlib import Path

import pandas as pd

from .config_loader import IS_SIDE_WORKSPACE, PROJECT_ROOT, WORKSPACE_ROOT, load_yaml
from .outcome_category import _MEASURE_ONLY_CATEGORIES, RULES

# A side workspace keeps its own copy next to its analysis outputs (never overwrites docs/category_mapping.md).
CATEGORY_MAPPING_MD = WORKSPACE_ROOT / "analysis" / "category_mapping.md" if IS_SIDE_WORKSPACE else PROJECT_ROOT / "docs" / "category_mapping.md"
INTERVENTION_CONFIG = PROJECT_ROOT / "config" / "intervention_categories.yaml"

OUTCOME_ORDER = [
    "pain_recovery",
    "pain_interference",
    "feasibility_acceptability",
    "mechanistic",
    "mood",
    "physical_performance",
    "associated_symptoms",
    "healthcare_use_cost",
    "other",
]
MEASURE_NAME_MARK = " †"


def _pretty(pattern: str) -> str:
    """Readable form of a regex fragment for a markdown table cell."""
    p = re.sub(r"\(\?[!<=][^)]*\)", "", pattern)
    p = p.replace(r"\s*", "").replace(r"\s+", " ").replace(r"\s", " ").replace(r"\d", "<n>")
    p = p.replace("[- ]?", "-").replace("[- ]", "-").replace("(?:", "(").replace(r"\b", "")
    p = p.replace("\\", "")
    return p.replace("|", "\\|")


def _outcome_patterns() -> dict[tuple[str, str], list[str]]:
    patterns: dict[tuple[str, str], list[str]] = {}
    for rule in RULES:
        mark = MEASURE_NAME_MARK if rule.measure_only and rule.category not in _MEASURE_ONLY_CATEGORIES else ""
        cell = patterns.setdefault((rule.category, rule.subcategory), [])
        cell.extend(_pretty(p) + mark for p in rule.patterns)
    return patterns


def _top_instruments(outcomes: pd.DataFrame) -> dict[tuple[str, str], str]:
    counts: dict[tuple[str, str], Counter[str]] = {}
    for row in outcomes.itertuples():
        for name in str(row.instruments_detected).split("|"):
            name = name.strip()
            if name and name != "nan":
                counts.setdefault((row.outcome_category, row.outcome_subcategory), Counter())[name] += 1
    return {k: ", ".join(f"{n} ({c})" for n, c in v.most_common(4)) for k, v in counts.items()}


def outcome_table(outcomes: pd.DataFrame) -> str:
    total = len(outcomes)
    patterns = _outcome_patterns()
    instruments = _top_instruments(outcomes)
    cat_rows = outcomes.groupby("outcome_category").size()
    cat_trials = outcomes.groupby("outcome_category")["nct_id"].nunique()
    sub = (
        outcomes.groupby(["outcome_category", "outcome_subcategory"])
        .agg(rows=("outcome_id", "size"), trials=("nct_id", "nunique"))
        .reset_index()
    )
    lines = [
        f"| Category | Subcategory | Rows (% of {total:,}) | Trials | Patterns | Most frequent detected instruments |",
        "|---|---|---:|---:|---|---|",
    ]
    for cat in OUTCOME_ORDER:
        if cat not in cat_rows:
            continue
        note = " *(measure name only)*" if cat in _MEASURE_ONLY_CATEGORIES else ""
        lines.append(
            f"| **{cat}**{note} | | **{cat_rows[cat]} ({cat_rows[cat] / total:.1%})** | **{cat_trials[cat]}** | | |"
        )
        for row in sub[sub.outcome_category == cat].sort_values("rows", ascending=False).itertuples():
            key = (cat, row.outcome_subcategory)
            cell = ", ".join(patterns.get(key, [])) or "—"
            lines.append(
                f"| | {row.outcome_subcategory} | {row.rows} ({row.rows / total:.1%}) | {row.trials} "
                f"| {cell} | {instruments.get(key, '—')} |"
            )
    return "\n".join(lines)


def intervention_tables(studies: pd.DataFrame, config: dict) -> str:
    total = len(studies)
    per_category: Counter[str] = Counter()
    for value in studies["intervention_categories"].fillna(""):
        for cat in {c.strip() for c in str(value).split("|") if c.strip()}:
            per_category[cat] += 1

    lines = [
        f"| Category | Label | Trials (% of {total}) | Patterns (arm name + description + type) |",
        "|---|---|---:|---|",
    ]
    categories: OrderedDict[str, dict] = OrderedDict(config["categories"])
    for cat, spec in categories.items():
        cell = ", ".join(_pretty(p) for p in spec.get("patterns", [])) or "—"
        lines.append(f"| `{cat}` | {spec.get('label', cat)} | {per_category[cat]} ({per_category[cat] / total:.1%}) | {cell} |")
    other = per_category["other_behavioral_treatment"]
    lines.append(
        f"| `other_behavioral_treatment` | Other behavioral treatment | {other} ({other / total:.1%}) "
        "| fallback: an active behavioral arm (type `BEHAVIORAL`, or `OTHER` with behavioral wording) that matches no category above |"
    )

    n_none = int((studies["intervention_categories"].fillna("") == "").sum())
    n_multi = int(studies["is_multimodal"].astype(str).eq("True").sum())
    n_control = int((studies["control_arm_types"].fillna("") != "").sum())
    control = config.get("control_arm", {})
    modalities = "; ".join(
        f"{name}: {', '.join(spec['intervention_types'])}"
        for name, spec in config.get("multimodal_modalities", {}).items()
    )
    extra = [
        "",
        f"- Trials with more than one category are counted in each; trials with no category: {n_none}.",
        f"- `is_multimodal` (a category plus an active non-behavioral arm): {n_multi} trials ({n_multi / total:.1%}). "
        f"Non-behavioral arm types: {modalities}.",
        f"- Trials with at least one comparator arm: {n_control} ({n_control / total:.1%}). Comparator arms never contribute categories.",
        "",
        "**Comparator arm patterns** (arm name only): "
        + ", ".join(_pretty(p) for p in control.get("patterns", [])),
        "",
        "**Comparator exclusions** (names that look like controls but are active): "
        + ", ".join(_pretty(p) for p in control.get("exclude_patterns", [])),
    ]
    return "\n".join(lines + extra)


def write_category_mapping(
    studies: pd.DataFrame,
    outcomes: pd.DataFrame,
    path: Path = CATEGORY_MAPPING_MD,
    *,
    extraction_run_id: str = "",
    rules_version: str = "",
) -> Path:
    included_studies = studies[studies["cohort_inclusion_status"] == "included"]
    included_outcomes = outcomes[outcomes["cohort_inclusion_status"] == "included"]
    config = load_yaml(INTERVENTION_CONFIG)

    text = f"""# Category mapping: outcomes and interventions

**Generated automatically by `finalize_cohort` (`src/ctgov_pipeline/category_mapping_report.py`). Do not edit by hand:** it is rewritten on every rebuild, so the patterns and counts always match the code, `config/intervention_categories.yaml` and the included cohort.

Cohort: {len(included_studies)} included trials, {len(included_outcomes):,} primary-outcome rows (extraction run `{extraction_run_id}`, rules `{rules_version}`). Categories are descriptive aids for review only; they never include or exclude a trial or an outcome, and never replace the raw text.

## Outcome categories (`outcome_category`, `outcome_subcategory` in `primary_outcomes.csv`)

Each primary outcome gets one category. Rules run as one ordered list (the order of the table below, with the measure-name-only rules last); the **first rule with a matching pattern wins**; no match gives `other` with `outcome_category_review_flag = True`.

Patterns read the measure + description + time frame, except all `mechanistic` and `feasibility_acceptability` patterns and the patterns marked † , which read the **measure name only** (descriptions of clinical outcomes mention "fMRI", "enrollment", "adverse", "attend" or "consent" without being those outcomes; the † patterns are generic words, so they are tried last and cannot override a specific rule). Patterns are shown as readable regex fragments (`?` optional, `<n>` a number). "Most frequent detected instruments" comes from the separate `instruments_detected` lexicon column, not from these rules.

{outcome_table(included_outcomes)}

## Intervention categories (`intervention_categories` in `studies.csv`)

Multi-label, taxonomy v{config.get("version", "")}: each trial gets every category matched by any **active** (non-comparator) arm, using the arm name, description and type. Comparator arms are detected from the arm **name** only and never contribute a category.

{intervention_tables(included_studies, config)}
"""
    path.write_text(text, encoding="utf-8")
    return path
